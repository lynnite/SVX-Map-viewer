function addMapLabels(container, activeMapFile) {
  if (!container) return;
  container.querySelectorAll('.custom-map-label').forEach(el => el.remove());

  const targets = (window.MAP_LABELS || []).filter(l => !l.map || l.map === activeMapFile);
  targets.forEach(l => {
    const div = document.createElement("div");
    div.textContent = l.uppercase ? l.text.toUpperCase() : l.text;
    div.className = "custom-map-label";

    let stroke = l.strokeOn
      ? `text-shadow: -${l.strokeWidth}px -${l.strokeWidth}px 0 ${l.strokeColor}, ${l.strokeWidth}px -${l.strokeWidth}px 0 ${l.strokeColor}, -${l.strokeWidth}px ${l.strokeWidth}px 0 ${l.strokeColor}, ${l.strokeWidth}px ${l.strokeWidth}px 0 ${l.strokeColor};`
      : '';
    let pill = l.pillOn
      ? `background: ${l.pillColor}${Math.round((l.pillOpacity||0.5)*255).toString(16).padStart(2,'0')}; padding: 4px 10px; border-radius: 5px;`
      : '';

    div.style.cssText = `position:absolute;left:${l.pixelX}px;top:${l.pixelY}px;transform:translate(-50%,-50%) rotate(${l.rotation}deg);` +
      `font-family:'${l.fontFamily}',sans-serif;font-size:${l.fontSize}px;font-weight:${l.bold?700:400};` +
      `font-style:${l.italic?'italic':'normal'};letter-spacing:${l.letterSpacing}px;color:${l.color};` +
      (l.uppercase?'text-transform:uppercase;':'') + stroke + pill +
      `white-space:nowrap;pointer-events:none;user-select:none;z-index:50;`;

    container.appendChild(div);
  });
}